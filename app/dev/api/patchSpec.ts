/**
 * Supabase's REST API (PostgREST) publishes a Swagger 2.0 spec whose `host` is the
 * address inside its container (e.g. `0.0.0.0:3000`). Point it at the public
 * Supabase URL so Swagger UI's "Try it out" requests reach the API.
 */
export interface SwaggerSpec {
  swagger?: string;
  host?: string;
  basePath?: string;
  schemes?: string[];
  info?: Record<string, unknown>;
  [key: string]: unknown;
}

export function patchPostgrestSpec(spec: SwaggerSpec, supabaseUrl: string): SwaggerSpec {
  const url = new URL(supabaseUrl);
  const basePath = `${url.pathname.replace(/\/$/, '')}/rest/v1`;
  return {
    ...spec,
    host: url.host,
    basePath,
    schemes: [url.protocol.replace(':', '')],
    info: {
      ...spec.info,
      title: 'Music app database API (Supabase REST)',
      description:
        'Auto-generated by PostgREST from the `public` schema. Requests run as the signed-in ' +
        'user (or `anon`), so row-level security applies.',
    },
  };
}
