-- SHR-05 · Store share tokens hashed (CR SHR-01-hash-share-tokens; REQ-SHARE-01, REQ-SHARE-03)
--
-- shares.token held the bearer token itself, so anyone who could read the table (a backup,
-- a leaked read credential, a log) could open every live link. From now on only
-- sha256(token) (`token_hash`) and the first 6 characters (`token_prefix`, display only) are
-- stored. The app hashes the token from the share URL and looks it up by `token_hash`.
--
-- Deploy safety (step 1 of 2). Vercel applies this migration while the previous build is
-- still serving, and that build inserts and reads `token`:
--   * existing rows are backfilled, so links made before this migration keep opening;
--   * `token` becomes nullable but stays, so the old build can still read the links it knows;
--   * a trigger fills `token_hash` / `token_prefix` from `token` on insert, so the old build's
--     inserts (which only set `token`) still satisfy the new NOT NULL columns.
-- The new build never writes or reads `token`. A later migration (step 2) nulls and drops
-- `token` and this trigger once no build that uses them is live.
--
-- Column changes were generated by drizzle-kit from db/schema/shares.ts; the backfill and
-- trigger are by hand. sha256() is built into Postgres 11+, no extension needed.

ALTER TABLE "shares" ALTER COLUMN "token" DROP NOT NULL;--> statement-breakpoint
ALTER TABLE "shares" ADD COLUMN "token_hash" "bytea";--> statement-breakpoint
ALTER TABLE "shares" ADD COLUMN "token_prefix" text;--> statement-breakpoint
UPDATE "shares"
SET "token_hash" = sha256(convert_to("token", 'UTF8')),
    "token_prefix" = left("token", 6)
WHERE "token" IS NOT NULL;--> statement-breakpoint
ALTER TABLE "shares" ALTER COLUMN "token_hash" SET NOT NULL;--> statement-breakpoint
ALTER TABLE "shares" ALTER COLUMN "token_prefix" SET NOT NULL;--> statement-breakpoint
ALTER TABLE "shares" ADD CONSTRAINT "shares_token_hash_key" UNIQUE("token_hash");--> statement-breakpoint

-- Old-build compatibility: rows inserted with only `token` get their hash and prefix here.
-- Dropped together with `token` in step 2.
CREATE OR REPLACE FUNCTION public.shares_fill_token_hash()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
  IF NEW.token IS NOT NULL THEN
    NEW.token_hash := sha256(convert_to(NEW.token, 'UTF8'));
    NEW.token_prefix := left(NEW.token, 6);
  END IF;
  RETURN NEW;
END;
$$;--> statement-breakpoint
DROP TRIGGER IF EXISTS shares_fill_token_hash ON public.shares;--> statement-breakpoint
CREATE TRIGGER shares_fill_token_hash
BEFORE INSERT OR UPDATE OF token ON public.shares
FOR EACH ROW EXECUTE FUNCTION public.shares_fill_token_hash();
